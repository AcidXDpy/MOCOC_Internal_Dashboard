export function classifyMember(member: Member): NaicsClassification {
  const match = crosswalk[member.industry] ?? fallback;
  return {
    code: match.code,
    title: match.title,
    confidence: match.confidence,
    method: "category_crosswalk",
    evidence: [
      `Chamber category: ${member.industry}`,
      member.notes
        ? "Public directory description available for human review"
        : "No public description available",
    ],
    verificationStatus: match.confidence >= 0.8 ? "suggested" : "needs_review",
    updatedAt: "2026-07-17",
  };
}

export function getClassificationDefaults(member: Member) {
  const match = crosswalk[member.industry] ?? fallback;
  return {
    industryGroup: match.group,
    audience: match.audience,
    operatingModel: match.operatingModel,
  };
}

export function naicsSector(code: string) {
  return code.slice(0, 2);
}
